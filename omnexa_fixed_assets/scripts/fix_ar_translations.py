def main() -> None:
	rows: list[tuple[str, str]] = []
	missing: list[str] = []

	with CSV_PATH.open(encoding="utf-8") as handle:
		reader = csv.reader(handle)
		for row in reader:
			if not row:
				continue
			source = row[0]
			if source in TRANSLATIONS:
				rows.append((source, TRANSLATIONS[source]))
			elif source.startswith("{"):
				# already Arabic source rows at file end
				rows.append((source, row[1] if len(row) > 1 else source))
			else:
				missing.append(source)
				rows.append((source, source))

	with CSV_PATH.open("w", encoding="utf-8", newline="") as handle:
		writer = csv.writer(handle, lineterminator="\n")
		writer.writerows(rows)

	print(f"Updated {len(rows)} rows in {CSV_PATH}")
	if missing:
		print(f"Warning: {len(missing)} rows kept as English (no translation entry)")


if __name__ == "__main__":
	main()
